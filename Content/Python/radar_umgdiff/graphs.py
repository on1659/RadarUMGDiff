"""그래프 바이너리 리더 (dev 문서 §11.7 M4 행, §11.9 UEdGraphNode·UK2Node_EditablePinBase).

근거 (5.8):
- FEdGraphPinType::Serialize           Runtime/Engine/Private/EdGraph/EdGraphPin.cpp 163~345
- operator<<(FEdGraphTerminalType)     Runtime/Engine/Private/EdGraph/EdGraphNode.cpp 48~110
- operator<<(FSimpleMemberReference)   Runtime/Engine/Classes/EdGraph/EdGraphPin.h 66
- UEdGraphPin::Serialize               EdGraphPin.cpp 1838~1960 (본문), SerializePinArray 2063, SerializePin 2132~2293
- UEdGraphNode::Serialize              EdGraphNode.cpp 212~262 — 태그·GUID 뒤에 FBlueprintsObjectVersion >= EdGraphPinOptimized 면 핀 배열
- operator<<(FUserPinInfo)             Editor/BlueprintGraph/Private/K2Node_EditablePinBase.cpp 80~136, 배열은 254~ (노드 핀 배열 뒤)

JSON 멤버 이름은 네이티브 생산자가 리플렉션으로 내는 이름(FEdGraphPinType 의 UPROPERTY)과 같다.
"""

from .reader import ParseError
from .text import read_text
from . import versions as V

# EPinContainerType (EdGraphNode.h 123) — 네이티브 ToJson 은 enum class 이름을 "형::멤버" 로 낸다
CONTAINER_TYPES = ["EPinContainerType::None", "EPinContainerType::Array", "EPinContainerType::Set", "EPinContainerType::Map"]
# EEdGraphPinDirection (EdGraphPin.h) EGPD_Input 0, EGPD_Output 1
PIN_DIRECTIONS = ["EGPD_Input", "EGPD_Output"]


def _name_or_string(r, pkg):
    """FFrameworkObjectVersion >= PinsStoreFName 이면 FName, 아니면 FString."""
    if V.at_least(pkg, "FFrameworkObjectVersion", "PinsStoreFName"):
        return r.fname()
    return r.fstring()


def read_terminal_type(r, pkg):
    out = {"TerminalCategory": _name_or_string(r, pkg), "TerminalSubCategory": _name_or_string(r, pkg)}
    out["TerminalSubCategoryObject"] = pkg.object_path(r.i32())
    out["bTerminalIsConst"] = r.bool32()
    out["bTerminalIsWeakPointer"] = r.bool32()
    out["bTerminalIsUObjectWrapper"] = r.bool32() if V.at_least(pkg, "FReleaseObjectVersion", "PinTypeIncludesUObjectWrapperFlag") else False
    return out


def default_terminal_type():
    return {"TerminalCategory": "None", "TerminalSubCategory": "None", "TerminalSubCategoryObject": None,
            "bTerminalIsConst": False, "bTerminalIsWeakPointer": False, "bTerminalIsUObjectWrapper": False}


def read_pin_type(r, pkg):
    if not V.at_least(pkg, "FFrameworkObjectVersion", "EdGraphPinContainerType"):
        raise ParseError("EdGraphPinContainerType 이전 핀 타입 형식은 5.x 저장본에 없다")
    out = {"PinCategory": _name_or_string(r, pkg), "PinSubCategory": _name_or_string(r, pkg)}
    out["PinSubCategoryObject"] = pkg.object_path(r.i32())
    container = r.u8()
    if container >= len(CONTAINER_TYPES):
        raise ParseError("EPinContainerType 값 이상: %d" % container)
    value_type = read_terminal_type(r, pkg) if container == 3 else default_terminal_type()
    is_reference = r.bool32()
    is_weak = r.bool32()
    member = {"MemberParent": pkg.object_path(r.i32()), "MemberName": r.fname(), "MemberGuid": r.fguid()}
    is_const = r.bool32()
    is_wrapper = r.bool32() if V.at_least(pkg, "FReleaseObjectVersion", "PinTypeIncludesUObjectWrapperFlag") else False
    single = r.bool32() if V.at_least(pkg, "FUE5ReleaseStreamObjectVersion", "SerializeFloatPinDefaultValuesAsSinglePrecision") else (out["PinCategory"] == "float")
    # 네이티브 리플렉션 멤버 순서 (EdGraphPin.h FEdGraphPinType)
    return {
        "PinCategory": out["PinCategory"], "PinSubCategory": out["PinSubCategory"], "PinSubCategoryObject": out["PinSubCategoryObject"],
        "PinSubCategoryMemberReference": member, "PinValueType": value_type, "ContainerType": CONTAINER_TYPES[container],
        "bIsReference": is_reference, "bIsConst": is_const, "bIsWeakPointer": is_weak, "bIsUObjectWrapper": is_wrapper,
        "bSerializeAsSinglePrecisionFloat": single,
    }


def _pin_ref(r):
    """SerializePin 의 참조 형식 (LinkedTo·SubPins·ParentPin…): bool 널 + [FPackageIndex 노드 + FGuid 핀]."""
    if r.bool32():
        return None
    return {"node": r.i32(), "pinId": r.fguid()}


def _pin_ref_array(r):
    n = r.i32()
    if n < 0 or n > 100000:
        raise ParseError("핀 참조 배열 길이 이상: %d" % n)
    return [_pin_ref(r) for _ in range(n)]


def read_pin_body(r, pkg):
    pin = {"owningNode": r.i32(), "pinId": r.fguid(), "name": _name_or_string(r, pkg)}
    pin["friendlyName"] = read_text(r, pkg)          # 에디터 저장본(필터 없음)에는 항상 있다
    if V.at_least(pkg, "FUE5MainStreamObjectVersion", "EdGraphPinSourceIndex"):
        pin["sourceIndex"] = r.i32()
    pin["toolTip"] = r.fstring()
    d = r.u8()
    pin["direction"] = PIN_DIRECTIONS[d] if d < len(PIN_DIRECTIONS) else d
    pin["pinType"] = read_pin_type(r, pkg)
    pin["defaultValue"] = r.fstring()
    pin["autogeneratedDefaultValue"] = r.fstring()
    pin["defaultObject"] = pkg.object_path(r.i32())
    pin["defaultTextValue"] = read_text(r, pkg)
    pin["linkedTo"] = _pin_ref_array(r)
    pin["subPins"] = _pin_ref_array(r)
    pin["parentPin"] = _pin_ref(r)
    pin["referencePassThroughConnection"] = _pin_ref(r)
    pin["persistentGuid"] = r.fguid()
    pin["bitField"] = r.u32()
    return pin


def read_owned_pins(r, pkg):
    """UEdGraphPin::SerializeAsOwningNode: i32 수 + 원소마다 bool 널 + [노드 + 핀 GUID + 본문]."""
    n = r.i32()
    if n < 0 or n > 10000:
        raise ParseError("핀 배열 길이 이상: %d" % n)
    pins = []
    for _ in range(n):
        if r.bool32():
            pins.append(None)
            continue
        node = r.i32()
        guid = r.fguid()
        body = read_pin_body(r, pkg)
        if body["pinId"] != guid or body["owningNode"] != node:
            raise ParseError("핀 머리와 본문의 노드·GUID 가 다름")
        pins.append(body)
    return pins


def read_user_pins(r, pkg):
    """TArray<FUserPinInfo> (UK2Node_EditablePinBase)."""
    n = r.i32()
    if n < 0 or n > 10000:
        raise ParseError("사용자 핀 배열 길이 이상: %d" % n)
    out = []
    for _ in range(n):
        name = _name_or_string(r, pkg)
        pin_type = read_pin_type(r, pkg)
        d = r.u8()
        out.append({"PinName": name, "PinType": pin_type, "DesiredPinDirection": PIN_DIRECTIONS[d] if d < len(PIN_DIRECTIONS) else d,
                    "PinDefaultValue": r.fstring()})
    return out

